-- Run in Supabase SQL Editor. Store no secrets in this table.
create table if not exists public.jobs_table (
  id bigint generated by default as identity primary key,
  job_url text not null unique,
  job_title text,
  company text,
  processed_at timestamptz default now()
);
create index if not exists jobs_table_processed_at_idx on public.jobs_table (processed_at desc);
